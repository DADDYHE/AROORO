#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * TypeScript to JavaScript build helper for service modules
 * - Runs tsc with tsconfig.paymentService.json
 * - Prepends /* eslint-disable *\/ marker to refund.js so the generated
 *   file does not get flagged by project's strict style rules.
 *
 * 与 build-common.js 配套：
 *   - build-common.js 处理 cloudfunctions/common/*.ts
 *   - build-payment-service.js 处理 cloudfunctions/paymentService/services/*.ts
 *
 * 编译顺序：
 *   1) build-common：先产出 common/* 编译产物（errors.js、utils.js 等）
 *   2) build-payment-service：再产出 paymentService/services/*.js（依赖 common/*）
 */
const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
// Sprint 25: 扩展到 pay.ts（与 refund.ts 共享同一 tsconfig）
// Sprint 26: 扩展到 notify.ts（与 pay.ts / refund.ts 共享同一 tsconfig）
// Sprint 27: 扩展到 commission.ts（与 pay.ts / refund.ts / notify.ts 共享同一 tsconfig）
const TARGETS = [
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'refund.js'),
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'pay.js'),
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'notify.js'),
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'commission.js'),
]
const DISABLE = '/* eslint-disable -- auto-generated by tsc; style controlled by tsconfig */'

// 清理 tsc 可能产出的多余 common/ 副本（由于 rootDir 包含 common/）
//   - 预期结构：tsc 在 cloudfunctions 根下产出，但 paymentService/services 只需要 refund.js
//   - 删除 cloudfunctions/paymentService/services/common/（不应作为运行时入口）
//   - 删除 cloudfunctions/paymentService/services/paymentService/（嵌套产物）
const STALE_DIRS = [
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'common'),
  path.join(ROOT, 'cloudfunctions', 'paymentService', 'services', 'paymentService'),
]

console.log('[build:payment-service] cleaning stale tsc artifacts ...')
for (const dir of STALE_DIRS) {
  if (fs.existsSync(dir)) {
    fs.rmSync(dir, { recursive: true, force: true })
    const rel = path.relative(ROOT, dir)
    console.log(`[build:payment-service] removed ${rel}`)
  }
}

console.log('[build:payment-service] running tsc ...')
execSync('npx --yes -p typescript@5.4.5 tsc -p tsconfig.paymentService.json', {
  cwd: ROOT,
  stdio: 'inherit',
})

// 再次清理（tsc 会重新生成 common/ 副本）
for (const dir of STALE_DIRS) {
  if (fs.existsSync(dir)) {
    fs.rmSync(dir, { recursive: true, force: true })
    const rel = path.relative(ROOT, dir)
    console.log(`[build:payment-service] removed ${rel} (post-build)`)
  }
}

for (const TARGET of TARGETS) {
  if (fs.existsSync(TARGET)) {
    const original = fs.readFileSync(TARGET, 'utf8')
    if (!original.startsWith(DISABLE)) {
      fs.writeFileSync(TARGET, `${DISABLE}\n${original}`)
      const rel = path.relative(ROOT, TARGET)
      console.log(`[build:payment-service] prepended eslint-disable to ${rel}`)
    }
  }
}

console.log('[build:payment-service] done.')
