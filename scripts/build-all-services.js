/**
 * 构建单个服务
 */
function buildOne(svc) {
  const label = `[build:${svc.name}]`
  console.log(`${label} cleaning stale tsc artifacts ...`)
  for (const rel of svc.staleDirs) {
    const dir = path.join(ROOT, rel)
    if (fs.existsSync(dir)) {
      fs.rmSync(dir, { recursive: true, force: true })
      console.log(`${label} removed ${rel}`)
    }
  }

  console.log(`${label} running tsc (${svc.tsconfig}) ...`)
  execSync(`npx --yes -p typescript@5.4.5 tsc -p ${svc.tsconfig}`, {
    cwd: ROOT,
    stdio: 'inherit',
  })

  // 再次清理（tsc 会重新生成副本）
  for (const rel of svc.staleDirs) {
    const dir = path.join(ROOT, rel)
    if (fs.existsSync(dir)) {
      fs.rmSync(dir, { recursive: true, force: true })
      console.log(`${label} removed ${rel} (post-build)`)
    }
  }

  // 注入 eslint-disable 头
  for (const rel of svc.targets) {
    const file = path.join(ROOT, rel)
    if (fs.existsSync(file)) {
      const original = fs.readFileSync(file, 'utf8')
      if (!original.startsWith(DISABLE)) {
        fs.writeFileSync(file, `${DISABLE}\n${original}`)
        console.log(`${label} prepended eslint-disable to ${rel}`)
      }
    }
  }
  console.log(`${label} done.`)
}

function main() {
  const args = process.argv.slice(2)
  if (args.length > 0) {
    const selected = []
    for (const arg of args) {
      const svc = SERVICES.find(s => s.name === arg)
      if (!svc) {
        console.error(`[build-all-services] unknown service: ${arg}`)
        console.error(`[build-all-services] available: ${SERVICES.map(s => s.name).join(', ')}`)
        process.exit(1)
      }
      selected.push(svc)
    }
    for (const svc of selected) { buildOne(svc) }
    return
  }
  for (const svc of SERVICES) { buildOne(svc) }
}

main()
