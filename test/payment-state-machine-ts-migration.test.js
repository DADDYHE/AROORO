/**
 * Sprint 49 - payment-state-machine.js → .ts 迁移验证测试
 *
 * 目标：
 *   1. 验证 cloudfunctions/paymentService/common/payment-state-machine.ts 存在且为源文件
 *   2. 验证编译产物 payment-state-machine.js / .d.ts 存在
 *   3. 验证 .d.ts 包含核心导出
 *   4. 验证 tsconfig.paymentService.json 包含新文件
 *   5. 验证编译产物的功能与原 .js 行为一致
 *   6. 验证运行时导出与 .ts 源一致
 */

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const PAYMENT_COMMON = path.join(ROOT, 'cloudfunctions', 'paymentService', 'common')
const SRC = path.join(PAYMENT_COMMON, 'payment-state-machine.ts')
const JS = path.join(PAYMENT_COMMON, 'payment-state-machine.js')
const DTS = path.join(PAYMENT_COMMON, 'payment-state-machine.d.ts')

describe('Sprint 49: payment-state-machine.js → .ts 迁移', () => {
  test('payment-state-machine.ts 源文件应存在', () => {
    expect(fs.existsSync(SRC)).toBe(true)
  })

  test('编译产物 payment-state-machine.js 应存在', () => {
    expect(fs.existsSync(JS)).toBe(true)
  })

  test('类型声明 payment-state-machine.d.ts 应存在', () => {
    expect(fs.existsSync(DTS)).toBe(true)
  })

  test('.js 编译产物应含 eslint-disable 标记', () => {
    const js = fs.readFileSync(JS, 'utf8')
    expect(js).toContain('/* eslint-disable -- auto-generated by tsc')
  })

  test('.d.ts 应包含核心导出', () => {
    const dts = fs.readFileSync(DTS, 'utf8')
    expect(dts).toContain('paymentStateMachine')
    expect(dts).toContain('resolveOrderStatus')
    expect(dts).toContain('isKnownOrderType')
    expect(dts).toContain('ORDER_STATUS_ON_PAID')
    expect(dts).toContain('PaymentState')
    expect(dts).toContain('KnownOrderType')
  })

  test('tsconfig.paymentService.json 应包含 payment-state-machine.ts', () => {
    const cfg = JSON.parse(
      fs.readFileSync(path.join(ROOT, 'tsconfig.paymentService.json'), 'utf8')
    )
    expect(cfg.include).toContain(
      'cloudfunctions/paymentService/common/payment-state-machine.ts'
    )
  })

  test('build:paymentService 应处理 payment-state-machine.js（build-all-services.js TARGETS）', () => {
    const buildScript = fs.readFileSync(
      path.join(ROOT, 'scripts', 'build-all-services.js'),
      'utf8'
    )
    expect(buildScript).toMatch(/payment-state-machine\.js/)
  })

  test('编译后的 .js 仍能正确导出所有公共 API', () => {
    const api = require(JS)
    expect(api.paymentStateMachine).toBeDefined()
    expect(typeof api.resolveOrderStatus).toBe('function')
    expect(typeof api.isKnownOrderType).toBe('function')
    expect(api.ORDER_STATUS_ON_PAID).toBeDefined()
  })

  test('paymentStateMachine 应保持原有 5 个状态 + 转移表', () => {
    const { paymentStateMachine } = require(JS)
    expect(paymentStateMachine.initial).toBe('unpaid')
    expect(paymentStateMachine.states.sort()).toEqual(
      ['closed', 'paid', 'paying', 'refunded', 'unpaid']
    )
  })

  test('paymentStateMachine 转移表应保持原行为', () => {
    const { paymentStateMachine } = require(JS)
    expect(paymentStateMachine.canTransition('unpaid', 'paying')).toBe(true)
    expect(paymentStateMachine.canTransition('unpaid', 'paid')).toBe(true)
    expect(paymentStateMachine.canTransition('unpaid', 'refunded')).toBe(false)
    expect(paymentStateMachine.canTransition('paying', 'paid')).toBe(true)
    expect(paymentStateMachine.canTransition('paying', 'unpaid')).toBe(true)
    expect(paymentStateMachine.canTransition('paid', 'refunded')).toBe(true)
    expect(paymentStateMachine.isTerminal('refunded')).toBe(true)
    expect(paymentStateMachine.isTerminal('closed')).toBe(true)
  })

  test('resolveOrderStatus 行为应保持不变', () => {
    const { resolveOrderStatus } = require(JS)
    expect(resolveOrderStatus('order')).toBe('paid')
    expect(resolveOrderStatus('feeding')).toBe('confirmed')
    expect(resolveOrderStatus('activity')).toBe('confirmed')
    expect(resolveOrderStatus('unknown')).toBe('paid')
    expect(resolveOrderStatus(null)).toBe('paid')
    expect(resolveOrderStatus(undefined, 'custom')).toBe('custom')
  })

  test('isKnownOrderType 行为应保持不变', () => {
    const { isKnownOrderType } = require(JS)
    expect(isKnownOrderType('order')).toBe(true)
    expect(isKnownOrderType('mall')).toBe(true)
    expect(isKnownOrderType('tuan')).toBe(true)
    expect(isKnownOrderType('feeding')).toBe(true)
    expect(isKnownOrderType('activity')).toBe(true)
    expect(isKnownOrderType('unknown')).toBe(false)
    expect(isKnownOrderType(null)).toBe(false)
    expect(isKnownOrderType('')).toBe(false)
  })

  test('ORDER_STATUS_ON_PAID 应保持原映射', () => {
    const { ORDER_STATUS_ON_PAID } = require(JS)
    expect(Object.keys(ORDER_STATUS_ON_PAID).sort()).toEqual(
      ['activity', 'feeding', 'mall', 'order', 'tuan']
    )
    expect(ORDER_STATUS_ON_PAID.order).toBe('paid')
    expect(ORDER_STATUS_ON_PAID.mall).toBe('paid')
    expect(ORDER_STATUS_ON_PAID.tuan).toBe('paid')
    expect(ORDER_STATUS_ON_PAID.feeding).toBe('confirmed')
    expect(ORDER_STATUS_ON_PAID.activity).toBe('confirmed')
  })

  test('paymentStateMachine metadata 应保持完整', () => {
    const { paymentStateMachine } = require(JS)
    for (const s of ['unpaid', 'paying', 'paid', 'refunded', 'closed']) {
      const meta = paymentStateMachine.getMetadata(s)
      expect(meta).toBeDefined()
      expect(meta.label).toBeDefined()
      expect(meta.color).toMatch(/^#([0-9a-fA-F]{3,8})$/)
    }
  })
})
