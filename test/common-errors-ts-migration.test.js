/**
 * Sprint 11 - TypeScript 迁移验证测试
 *
 * 目标：
 *   1. 验证 cloudfunctions/common/errors.ts 存在且为源文件
 *   2. 验证编译产物 errors.js / errors.d.ts 存在
 *   3. 验证编译产物与 .ts 行为一致（导入后功能可用）
 *   4. 验证类型导出与 .d.ts 一致
 */

const fs = require('fs')
const path = require('path')

const COMMON = path.resolve(__dirname, '..', 'cloudfunctions', 'common')

describe('Sprint 11: errors.js → .ts 迁移', () => {
  test('errors.ts 源文件应存在', () => {
    expect(fs.existsSync(path.join(COMMON, 'errors.ts'))).toBe(true)
  })

  test('编译产物 errors.js 应存在', () => {
    expect(fs.existsSync(path.join(COMMON, 'errors.js'))).toBe(true)
  })

  test('类型声明 errors.d.ts 应存在', () => {
    expect(fs.existsSync(path.join(COMMON, 'errors.d.ts'))).toBe(true)
  })

  test('errors.js 应含 eslint-disable 标记（tsc 产物，lint 由 .eslintrc.json override 处理）', () => {
    const js = fs.readFileSync(path.join(COMMON, 'errors.js'), 'utf8')
    // Sprint 39：tsc 会在 CommonJS 模式下自动在第一行插入 "use strict";
    // 所以 eslint-disable 标记不再位于第 1 行；改用 .includes 检查
    expect(js).toContain('/* eslint-disable -- auto-generated by tsc')
  })

  test('编译后的 .js 仍能正确导出所有公共 API', () => {
    const api = require(path.join(COMMON, 'errors.js'))
    expect(typeof api.BusinessError).toBe('function')
    expect(typeof api.BusinessErrors).toBe('object')
    expect(typeof api.err).toBe('function')
    expect(typeof api.isBusinessError).toBe('function')
    expect(typeof api.wrapUnknown).toBe('function')
    expect(typeof api.toResponse).toBe('function')
    expect(typeof api.withErrorHandling).toBe('function')
  })

  test('.d.ts 应包含 BusinessError / BusinessErrors / 工厂函数', () => {
    const dts = fs.readFileSync(path.join(COMMON, 'errors.d.ts'), 'utf8')
    expect(dts).toContain('BusinessError')
    expect(dts).toContain('BusinessErrors')
    expect(dts).toContain('export declare function err')
    expect(dts).toContain('export declare function withErrorHandling')
  })

  test('tsconfig.common.json 应存在并配置为 emit', () => {
    const cfg = JSON.parse(
      fs.readFileSync(path.resolve(__dirname, '..', 'tsconfig.common.json'), 'utf8')
    )
    expect(cfg.compilerOptions.declaration).toBe(true)
    expect(cfg.include).toContain('cloudfunctions/common/errors.ts')
  })

  test('build:common 脚本应在 package.json 中', () => {
    const pkg = JSON.parse(
      fs.readFileSync(path.resolve(__dirname, '..', 'package.json'), 'utf8')
    )
    // Sprint 49: build:common 已统一指向 build:all-services.js
    expect(pkg.scripts['build:common']).toBe('node scripts/build-all-services.js')
  })

  test('utils.d.ts shim 应存在（errors.ts 编译时需要）', () => {
    expect(fs.existsSync(path.join(COMMON, 'utils.d.ts'))).toBe(true)
  })

  test('迁移不应改变公共 API 行为', () => {
    const { BusinessError, err, toResponse } = require(path.join(COMMON, 'errors.js'))
    const { ERROR_CODES } = require(path.join(COMMON, 'utils.js'))

    // 构造 + 序列化
    const e = err('ORDER_NOT_FOUND', '订单不存在', { orderId: 'ord_xyz' })
    expect(e).toBeInstanceOf(BusinessError)
    expect(e.code).toBe('ORDER_NOT_FOUND')
    expect(e.httpStatus).toBe(404)

    const res = toResponse(e)
    expect(res.code).toBe(ERROR_CODES.NOT_FOUND)
    expect(res.message).toBe('订单不存在')
    expect(res.error.type).toBe('ORDER_NOT_FOUND')
  })
})
